#include "ft/ft_linked_list.h"

t_list	*ft_lstmap(t_list *lst, void *(*f)(void *), void (*del)(void *))
{
	t_list	*new_lst;
	t_list	**tail;
	t_list	*node;
	void	*content;

	if (!f || !del)
		return (NULL);
	new_lst = NULL;
	tail = &new_lst;
	while (lst)
	{
		content = f(lst->content);
		node = ft_lstnew(content);
		if (!node)
		{
			del(content);
			ft_lstclear(&new_lst, del);
			return (NULL);
		}
		*tail = node;
		tail = &node->next;
		lst = lst->next;
	}
	return (new_lst);
}
